//! Commander's soul, identity and core memory. `SOUL.md`, `USER.md` and `identity.json` are the
//! editable sources; `CLAUDE.md` / `AGENTS.md` are generated from them (plus memory and projects)
//! right before every Commander turn. Every change to SOUL.md / USER.md keeps a revision.
use crate::commander::{write_atomic, Memory, LOCK, NAME};
use crate::runtime::{Project, Runtime};
use serde::{Deserialize, Serialize};
use serde_json::{json, Value};
use std::{fs, io::Write, path::Path};

pub const DEFAULT_SOUL: &str = "Friendly, warm and brief. Short answers, no filler, no long lists unless asked. Proactive: notice what would help the user next and offer it as a yes/no proposal. Plain language. Celebrate finished work in one line.\n";
/// The SOUL.md that earlier builds seeded. It is replaced by the new default only when untouched.
pub const LEGACY_SOUL: &str = r#"# Soul

Friendly, concise and warm. A calm chief of staff who is glad to help and does not waste words.

- Talk like a person: one to three short sentences by default.
- Lead with the result, then what is needed from the user, if anything.
- Light humour is fine. Never gush, never lecture, never pad.
- Be honest about what is done, what is waiting on the user and what failed.
- Use the user's own words for their projects and people.
"#;
pub const USER_TEMPLATE: &str = "# About the user\n\n- Who they are and what they do:\n- Role and company:\n- Preferences and how they like to work:\n- Key people:\n";
pub const GENERATED_HEADER: &str = "<!-- Generated by Freddai, edit SOUL.md / USER.md instead -->";
const MEMORY_BUDGET: usize = 1500;
const MAX_FILE_BYTES: usize = 100 * 1024;
const MAX_REVISIONS: usize = 50;

#[derive(Clone, Serialize, Deserialize, Debug, PartialEq)]
pub struct Revision {
    pub file: String,
    pub at: String,
    pub by: String,
    pub reason: String,
}

fn event(name: &str, error: &str) {
    eprintln!("{}", json!({"event":name,"error":error}));
}
fn file_name(file: &str) -> Result<&'static str, String> {
    match file {
        "soul" => Ok("SOUL.md"),
        "user" => Ok("USER.md"),
        _ => Err("file must be \"soul\" or \"user\"".into()),
    }
}
fn read_text(dir: &Path, name: &str) -> Result<String, String> {
    fs::read_to_string(dir.join(name)).map_err(|e| format!("Cannot read {name}: {e}"))
}
fn iso(t: chrono::DateTime<chrono::Utc>) -> String {
    t.to_rfc3339_opts(chrono::SecondsFormat::Millis, true)
}
fn revision_path(dir: &Path, file: &str, at: &str) -> std::path::PathBuf {
    dir.join("revisions").join(file).join(format!("{}.md", at.replace(':', "-")))
}

// ---------------------------------------------------------------- identity

pub fn read_name(dir: &Path) -> Result<String, String> {
    match fs::read(dir.join("identity.json")) {
        Ok(bytes) => {
            let v: Value = serde_json::from_slice(&bytes).map_err(|e| format!("Cannot read identity.json (left untouched): {e}"))?;
            Ok(v["name"].as_str().map(str::trim).filter(|n| !n.is_empty()).unwrap_or(NAME).to_string())
        }
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(NAME.to_string()),
        Err(e) => Err(format!("Cannot read identity.json: {e}")),
    }
}
fn write_name(dir: &Path, name: &str) -> Result<(), String> {
    write_atomic(&dir.join("identity.json"), serde_json::to_vec_pretty(&json!({"name":name})).map_err(|e| e.to_string())?.as_slice())
}

// ---------------------------------------------------------------- seeding

/// Create identity.json, USER.md and SOUL.md when missing. An untouched legacy SOUL.md is upgraded.
pub fn seed(dir: &Path) -> Result<(), String> {
    let _g = LOCK.lock().unwrap();
    fs::create_dir_all(dir.join("revisions")).map_err(|e| format!("Cannot create revisions folder: {e}"))?;
    if !dir.join("identity.json").exists() {
        write_name(dir, NAME)?;
    }
    if !dir.join("USER.md").exists() {
        write_atomic(&dir.join("USER.md"), USER_TEMPLATE.as_bytes())?;
    }
    let soul = dir.join("SOUL.md");
    match fs::read_to_string(&soul) {
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => write_atomic(&soul, DEFAULT_SOUL.as_bytes())?,
        Err(e) => return Err(format!("Cannot read SOUL.md: {e}")),
        Ok(current) if current == LEGACY_SOUL => {
            // Keep the old text restorable, then switch to the new default.
            add_revision(dir, "soul", LEGACY_SOUL, "commander", "Previous default")?;
            write_atomic(&soul, DEFAULT_SOUL.as_bytes())?;
            add_revision(dir, "soul", DEFAULT_SOUL, "commander", "Updated default soul")?;
        }
        Ok(_) => {}
    }
    Ok(())
}

// ---------------------------------------------------------------- revisions

fn add_revision(dir: &Path, file: &str, content: &str, by: &str, reason: &str) -> Result<Revision, String> {
    let mut t = chrono::Utc::now();
    let mut at = iso(t);
    while revision_path(dir, file, &at).exists() {
        t += chrono::Duration::milliseconds(1);
        at = iso(t);
    }
    let path = revision_path(dir, file, &at);
    fs::create_dir_all(path.parent().unwrap()).map_err(|e| format!("Cannot create revisions folder: {e}"))?;
    write_atomic(&path, content.as_bytes())?;
    let revision = Revision { file: file.into(), at, by: by.into(), reason: reason.into() };
    let line = serde_json::to_string(&revision).map_err(|e| e.to_string())?;
    let mut index = fs::OpenOptions::new().create(true).append(true).open(dir.join("revisions").join("index.jsonl"))
        .map_err(|e| format!("Cannot write revisions index: {e}"))?;
    writeln!(index, "{line}").map_err(|e| format!("Cannot write revisions index: {e}"))?;
    Ok(revision)
}
/// Newest first, at most 50.
pub fn revisions(dir: &Path) -> Result<Vec<Revision>, String> {
    let text = match fs::read_to_string(dir.join("revisions").join("index.jsonl")) {
        Ok(t) => t,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => return Ok(Vec::new()),
        Err(e) => return Err(format!("Cannot read revisions index: {e}")),
    };
    let mut all: Vec<Revision> = text.lines().filter(|l| !l.trim().is_empty()).filter_map(|l| {
        serde_json::from_str(l).map_err(|e| event("commander.revision_index_line_skipped", &e.to_string())).ok()
    }).collect();
    all.reverse();
    all.truncate(MAX_REVISIONS);
    Ok(all)
}

// ---------------------------------------------------------------- prompt

fn one_line(s: &str, max: usize) -> String {
    let flat = s.split_whitespace().collect::<Vec<_>>().join(" ");
    if flat.chars().count() > max { format!("{}...", flat.chars().take(max).collect::<String>()) } else { flat }
}
/// Active memories, pinned first then newest, within the character budget.
fn remembered(dir: &Path) -> Result<String, String> {
    let mut items: Vec<Memory> = match fs::read(dir.join("memory.json")) {
        Ok(b) if b.iter().all(u8::is_ascii_whitespace) => Vec::new(),
        Ok(b) => serde_json::from_slice(&b).map_err(|e| format!("Cannot read memory.json (left untouched): {e}"))?,
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Vec::new(),
        Err(e) => return Err(format!("Cannot read memory.json: {e}")),
    };
    let cutoff = chrono::Utc::now() - chrono::Duration::days(30);
    items.retain(|m| m.status == "active" && (m.pinned || chrono::DateTime::parse_from_rfc3339(&m.updated_at).map(|t| t >= cutoff).unwrap_or(true)));
    items.sort_by(|a, b| b.pinned.cmp(&a.pinned).then(b.updated_at.cmp(&a.updated_at)));
    let mut out = String::new();
    for m in items {
        let line = format!("- ({}) {}\n", m.kind, one_line(&m.text, 300));
        if out.chars().count() + line.chars().count() > MEMORY_BUDGET {
            break;
        }
        out.push_str(&line);
    }
    Ok(if out.is_empty() { "Nothing yet.\n".into() } else { out })
}
/// The exact CLAUDE.md / AGENTS.md text.
pub fn render_prompt(dir: &Path, projects: &[Project]) -> Result<String, String> {
    let name = read_name(dir)?;
    let soul = read_text(dir, "SOUL.md")?;
    let user = read_text(dir, "USER.md")?;
    let mut list = String::new();
    for p in projects.iter().filter(|p| !p.is_commander()) {
        let objective = p.objective.as_deref().map(str::trim).filter(|o| !o.is_empty()).map(|o| one_line(o, 300)).unwrap_or_else(|| "no objective yet".into());
        list.push_str(&format!("- {} (id: {}): {}\n", p.name, p.id, objective));
    }
    if list.is_empty() {
        list.push_str("No projects yet.\n");
    }
    Ok(format!(
        "{GENERATED_HEADER}\n\n{}\n## Identity\nYour name is {name}.\n\n## Soul\n{}\n\n## About the user\n{}\n\n## Remembered\n{}\n## Projects\n{}",
        crate::commander::ROLE.trim_end(), soul.trim(), user.trim(), remembered(dir)?, list
    ))
}
fn write_prompt_files(dir: &Path, text: &str) -> Result<(), String> {
    for file in ["CLAUDE.md", "AGENTS.md"] {
        let path = dir.join(file);
        if fs::read_to_string(&path).is_ok_and(|c| c == text) {
            continue;
        }
        write_atomic(&path, text.as_bytes())?;
    }
    Ok(())
}
/// Regenerate CLAUDE.md / AGENTS.md in `dir`. Failures are logged and returned.
pub fn refresh_in(dir: &Path, projects: &[Project]) -> Result<(), String> {
    render_prompt(dir, projects).and_then(|t| write_prompt_files(dir, &t)).map_err(|e| {
        event("commander.prompt_write_failed", &e);
        format!("Cannot prepare Commander's instructions: {e}")
    })
}
pub fn refresh(rt: &Runtime) -> Result<(), String> {
    let project = rt.commander_project().ok_or("Commander-in-Chief is not set up yet")?;
    refresh_in(Path::new(&project.path), &rt.snapshot().projects)
}
/// Hook run before EVERY thread turn (new launch, resume, queued continue). No-op for other projects.
pub fn before_launch(rt: &Runtime, project: &Project) -> Result<(), String> {
    if !project.is_commander() {
        return Ok(());
    }
    refresh_in(Path::new(&project.path), &rt.snapshot().projects)
}

// ---------------------------------------------------------------- profile

pub fn profile(rt: &Runtime) -> Result<Value, String> {
    let project = rt.commander_project().ok_or("Commander-in-Chief is not set up yet")?;
    let dir = Path::new(&project.path);
    let _g = LOCK.lock().unwrap();
    profile_locked(dir, &rt.snapshot().projects)
}
fn profile_locked(dir: &Path, projects: &[Project]) -> Result<Value, String> {
    Ok(json!({
        "name": read_name(dir)?,
        "soul": read_text(dir, "SOUL.md")?,
        "user": read_text(dir, "USER.md")?,
        "prompt_preview": render_prompt(dir, projects)?,
        "revisions": revisions(dir)?,
    }))
}
fn check_body(what: &str, body: &str) -> Result<(), String> {
    if body.len() > MAX_FILE_BYTES {
        return Err(format!("{what} is limited to 100 KB"));
    }
    Ok(())
}
/// Apply a partial profile change. `by` is "user" or "commander". A null/absent field is left alone.
pub fn save(rt: &Runtime, p: &Value, by: &str) -> Result<Value, String> {
    let project = rt.commander_project().ok_or("Commander-in-Chief is not set up yet")?;
    let dir = Path::new(&project.path);
    let field = |k: &str| -> Result<Option<String>, String> {
        match &p[k] {
            Value::Null => Ok(None),
            Value::String(s) => Ok(Some(s.clone())),
            _ => Err(format!("{k} must be a string")),
        }
    };
    let (name, soul, user, reason) = (field("name")?, field("soul")?, field("user")?, field("reason")?);
    let reason = reason.map(|r| r.trim().to_string()).filter(|r| !r.is_empty());
    if let Some(s) = &soul { check_body("SOUL.md", s)?; }
    if let Some(u) = &user { check_body("USER.md", u)?; }
    let name = match name {
        Some(n) => {
            let n = n.trim().to_string();
            if n.is_empty() || n.chars().count() > 80 {
                return Err("Name must be 1-80 characters".into());
            }
            Some(n)
        }
        None => None,
    };
    let _g = LOCK.lock().unwrap();
    for (key, file, value) in [("soul", "SOUL.md", &soul), ("user", "USER.md", &user)] {
        if let Some(value) = value {
            if read_text(dir, file)? != *value {
                write_atomic(&dir.join(file), value.as_bytes())?;
                add_revision(dir, key, value, by, reason.as_deref().unwrap_or("Edited"))?;
            }
        }
    }
    if let Some(name) = name {
        if read_name(dir)? != name {
            write_name(dir, &name)?;
        }
        if project.name != name {
            rt.update_project(&project.id, |p| p.name = name.clone())?;
        }
    }
    let projects = rt.snapshot().projects;
    refresh_in(dir, &projects)?;
    profile_locked(dir, &projects)
}
pub fn restore(rt: &Runtime, file: &str, at: &str) -> Result<Value, String> {
    file_name(file)?;
    let project = rt.commander_project().ok_or("Commander-in-Chief is not set up yet")?;
    let dir = Path::new(&project.path);
    {
        let _g = LOCK.lock().unwrap();
        if !revisions(dir)?.iter().any(|r| r.file == file && r.at == at) {
            return Err(format!("No {file} revision at {at}"));
        }
    }
    let body = fs::read_to_string(revision_path(dir, file, at)).map_err(|e| format!("Cannot read that revision: {e}"))?;
    save(rt, &json!({file: body, "reason": format!("Restored {at}")}), "user")
}

