import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const refreshConnection=async page=>{const button=page.getByRole('button',{name:'Refresh connection',exact:true});if(!await button.count())await page.getByRole('button',{name:/Connected to your Mac|Connecting to your Mac|Mac disconnected/}).click();await button.click()};
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const errors = []; page.on('pageerror', e => errors.push(e.message));
  const fixture = fileURLToPath(new URL('./fixtures/mobile-send.html', import.meta.url));
  await page.goto(`${process.env.FREDDAI_PREVIEW_URL || 'http://127.0.0.1:1420'}/@fs${fixture}`);
  await page.getByRole('button', { name: /Send latency/ }).click();
  const input = page.getByRole('textbox', { name: 'Reply', exact: true });
  await page.getByLabel('Permissions', { exact: true }).selectOption('bypass');
  await page.locator('summary[aria-label="Model and effort"]').click();
  await page.getByLabel('Model', { exact: true }).selectOption('opus');
  await page.getByLabel('Reasoning effort', { exact: true }).selectOption('max');
  await page.locator('summary[aria-label="Model and effort"]').click();
  await page.locator('input[type=file]').setInputFiles({ name: 'direction.txt', mimeType: 'text/plain', buffer: Buffer.from('Synthetic direction') });
  await page.getByRole('button', { name: 'Remove attachment direction.txt', exact: true }).waitFor();
  await input.fill('Queue this with my controls');
  await input.press('Enter');
  assert.equal(await input.inputValue(), 'Queue this with my controls\n', 'software Return keeps a multiline draft');
  assert.equal((await page.evaluate(() => window.composerCalls)).length, 0);
  await input.press('Control+Enter');
  await page.waitForFunction(() => window.composerCalls.length === 1);
  const call = (await page.evaluate(() => window.composerCalls))[0];
  assert.equal(call.options.permission_mode, 'bypass');
  assert.equal(call.options.model, 'opus');
  assert.equal(call.options.effort, 'max');
  assert.equal(call.options.attachments.length, 1);
  assert.equal(await input.inputValue(), '');
  await input.fill('A newer draft');
  await page.evaluate(() => window.rejectSend());
  await page.getByRole('alert').filter({ hasText: 'Synthetic send failure' }).waitFor();
  assert.equal(await input.inputValue(), 'Queue this with my controls\n\nA newer draft');
  await page.getByRole('button', { name: 'Remove attachment direction.txt', exact: true }).waitFor();
  await page.evaluate(() => window.setQueue());
  await refreshConnection(page);
  await page.getByRole('region', { name: 'Message queue' }).waitFor();
  await page.getByRole('button', { name: 'Pause', exact: true }).click();
  await page.getByRole('button', { name: 'Resume', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Resume', exact: true }).click();
  await page.getByRole('button', { name: 'Pause', exact: true }).waitFor();
  await page.getByRole('button', { name: 'Remove queued message: Pending direction', exact: true }).click();
  await page.getByRole('region', { name: 'Message queue' }).waitFor({ state: 'detached' });
  await page.getByRole('button', { name: 'Stop current turn and pause queue' }).click();
  await page.getByRole('button', { name: 'Send reply', exact: true }).waitFor();
  for (const width of [320, 375, 390, 430, 720]) {
    await page.setViewportSize({ width, height: 844 });
    await input.fill('Long multiline draft\n'.repeat(20));
    const layout = await page.locator('.companion-composer').evaluate(el => {
      const box = el.getBoundingClientRect();
      return { radius: getComputedStyle(el).borderRadius, overflow: el.scrollWidth > el.clientWidth, bottom: box.bottom, right: box.right, textHeight: el.querySelector('textarea').getBoundingClientRect().height };
    });
    assert.equal(layout.radius, '24px');
    assert.equal(layout.overflow, false, `composer overflow at ${width}`);
    assert.ok(layout.right <= width && layout.bottom <= 844);
    assert.ok(layout.textHeight <= 220);
    await page.locator('summary[aria-label="Model and effort"]').click();
    const menu = await page.locator('.agent-controls-panel').boundingBox();
    assert.ok(menu.x >= 0 && menu.x + menu.width <= width, `model menu fits ${width}`);
    await page.locator('summary[aria-label="Model and effort"]').click();
  }
  await page.getByRole('button', { name: 'Remove attachment direction.txt', exact: true }).click();
  await page.setViewportSize({ width: 390, height: 420 });
  await input.fill('Long draft with the keyboard open\n'.repeat(30));
  const keyboardBox = await page.locator('.companion-composer').boundingBox();
  assert.ok(keyboardBox.y + keyboardBox.height <= 420, 'send toolbar remains visible in reduced keyboard viewport');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ colorScheme: 'dark' });
  await input.fill('Review the composer on iPhone');
  await page.waitForFunction(() => getComputedStyle(document.querySelector('textarea')).color === 'rgb(227, 223, 238)');
  if (process.env.FREDDAI_LAYOUT_SCREENSHOTS) await page.screenshot({ path: `${process.env.FREDDAI_LAYOUT_SCREENSHOTS}/ios-composer.png` });
  assert.deepEqual(errors, []);
  console.log('PASS: mobile controls, attachments, failed-send recovery, queue/stop, multiline shortcuts, 320–720px layout');
} finally { await browser.close(); }
