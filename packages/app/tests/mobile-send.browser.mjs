import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser=await chromium.launch({headless:true,channel:'chrome'});
const refreshConnection=async page=>{const button=page.getByRole('button',{name:'Refresh connection',exact:true});if(!await button.count())await page.getByRole('button',{name:/Connected to your Mac|Connecting to your Mac|Mac disconnected/}).click();await button.click()};
try {
 const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.addInitScript(()=>{let visibility='visible';Object.defineProperty(document,'visibilityState',{get:()=>visibility});window.setSyntheticVisibility=value=>{visibility=value;document.dispatchEvent(new Event('visibilitychange'));};});
 const fixture=fileURLToPath(new URL('./fixtures/mobile-send.html',import.meta.url));
 await page.goto(`${process.env.FREDDAI_PREVIEW_URL || 'http://127.0.0.1:1420'}/@fs${fixture}`);
 await page.getByRole('button',{name:/Send latency/}).click();
 await page.getByRole('textbox',{name:'Reply',exact:true}).fill('Immediate synthetic message');
 await page.getByRole('button',{name:/^(Send reply|Queue message)$/,exact:true}).click();
 await page.getByRole('region',{name:'Message queue'}).getByText('Immediate synthetic message',{exact:true}).waitFor({timeout:700});
 assert.equal(await page.locator('article[data-role=user]').count(),0,'busy message goes straight into queue');
 assert.equal(await page.getByRole('textbox',{name:'Reply',exact:true}).inputValue(),'','composer clears before server acknowledgement');
 await page.evaluate(()=>window.acknowledgeSend());
 await page.waitForTimeout(100);
 assert.equal(await page.getByRole('textbox',{name:'Reply',exact:true}).inputValue(),'');
 assert.equal(await page.getByRole('region',{name:'Message queue'}).getByRole('listitem').count(),1,'acknowledged queue entry survives stale snapshots');
 await page.evaluate(()=>window.publishSend());
 await refreshConnection(page);
 await page.waitForTimeout(100);
 assert.equal(await page.locator('article[data-role=user]').count(),1,'snapshot replaces local preview without duplication');
 const calls=await page.evaluate(()=>window.snapshotCalls);
 await page.waitForFunction(previous=>window.snapshotCalls>previous,calls,{timeout:1800});
 await page.evaluate(()=>window.setSyntheticVisibility('hidden'));
 const beforeForeground=await page.evaluate(()=>window.snapshotCalls);
 await page.evaluate(()=>window.setSyntheticVisibility('visible'));
 await page.waitForFunction(previous=>window.snapshotCalls>previous,beforeForeground,{timeout:700});
 for(let i=0;i<2;i++) {
  await page.getByRole('textbox',{name:'Reply',exact:true}).fill('Immediate synthetic message');
  await page.getByRole('button',{name:/^(Send reply|Queue message)$/,exact:true}).click();
  await page.evaluate(()=>window.acknowledgeSend());
  await page.getByRole('textbox',{name:'Reply',exact:true}).fill('');
  await page.waitForTimeout(100);
 }
 assert.equal(await page.locator('article[data-role=user]').count(),1,'queued prompts stay out of transcript');
 assert.equal(await page.getByRole('region',{name:'Message queue'}).getByRole('listitem').count(),2,'identical queued prompts each retain a queue row');
 await page.evaluate(()=>window.publishSend());
 await refreshConnection(page);
 await page.waitForTimeout(100);
 assert.equal(await page.locator('article[data-role=user]').count(),2,'first identical prompt reconciles only one queue row');
 assert.equal(await page.getByRole('region',{name:'Message queue'}).getByRole('listitem').count(),1);
 await page.evaluate(()=>window.publishSend());
 await refreshConnection(page);
 await page.waitForTimeout(100);
 assert.equal(await page.locator('article[data-role=user]').count(),3,'both identical prompts reconcile without duplication');
 await page.getByRole('textbox',{name:'Reply',exact:true}).fill('Rejected synthetic message');
 await page.getByRole('button',{name:/^(Send reply|Queue message)$/,exact:true}).click();
 await page.getByRole('textbox',{name:'Reply',exact:true}).fill('Newer draft');
 await page.evaluate(()=>window.rejectSend());
 await page.getByRole('alert').filter({hasText:'Synthetic send failure'}).waitFor();
 assert.equal(await page.getByRole('textbox',{name:'Reply',exact:true}).inputValue(),'Rejected synthetic message\nNewer draft');
 assert.equal(await page.locator('article[data-role=user]').count(),3,'failed preview removed');
 await page.evaluate(()=>window.showDecision());
 await refreshConnection(page);
 await page.getByRole('button',{name:'Allow once',exact:true}).click();
 await page.getByRole('status').filter({hasText:'Allowed once · Sending…'}).waitFor({timeout:700});
 assert.equal(await page.getByRole('button',{name:'Allow once',exact:true}).count(),0);
 await page.evaluate(()=>window.rejectDecision());
 await page.getByRole('button',{name:'Allow once',exact:true}).waitFor();
 await page.getByRole('button',{name:'Decline',exact:true}).click();
 await page.evaluate(()=>window.acknowledgeDecision());
 await page.getByRole('status').filter({hasText:'Declined · Waiting for agent…'}).waitFor();
 await refreshConnection(page);
 await page.waitForTimeout(150);
 assert.equal(await page.getByRole('button',{name:'Decline',exact:true}).count(),0,'stale snapshot cannot re-enable submitted decision');
 await page.evaluate(()=>window.clearDecision());
 await page.getByRole('button',{name:'Back to threads',exact:true}).click();
 await page.getByRole('button',{name:'New thread',exact:true}).click();
 await page.getByRole('textbox',{name:'New thread prompt'}).fill('Immediate new task');
 await page.getByRole('button',{name:'Start thread',exact:true}).click();
 await page.locator('article[data-role=user]').filter({hasText:'Immediate new task'}).waitFor({timeout:700});
 await page.evaluate(()=>window.acknowledgeSend());
 await page.waitForTimeout(100);
 assert.equal(await page.locator('article[data-role=user]').filter({hasText:'Immediate new task'}).count(),1,'new thread preview survives missing snapshot');
 assert.deepEqual(errors,[]);
 console.log('PASS: immediate send, queued/stale snapshots, reconciliation, rejected draft, new thread continuity at iPhone size');
} finally {await browser.close();}
