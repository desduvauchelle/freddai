import {fileURLToPath} from 'node:url';
import assert from 'node:assert/strict';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const browser=await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_CHANNEL || 'chrome'});
const refreshConnection=async page=>{const button=page.getByRole('button',{name:'Refresh connection',exact:true});if(!await button.count())await page.getByRole('button',{name:/Connected to your Mac|Connecting to your Mac|Mac disconnected/}).click();await button.click()};
try {
 const page=await browser.newPage({viewport:{width:390,height:844}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 const base=process.env.FREDDAI_PREVIEW_URL || 'http://127.0.0.1:1420';
 const fixture=fileURLToPath(new URL('./fixtures/project-groups.html',import.meta.url));
 await page.goto(`${base}/@fs${fixture}`);
 const alpha=page.getByRole('region',{name:'Alpha threads',exact:true}),beta=page.getByRole('region',{name:'Beta threads',exact:true});
 await alpha.waitFor();
 assert.deepEqual(await page.locator('.companion-project-heading h2').allTextContents(),['Alpha','Beta','Empty project']);
 assert.equal(await alpha.locator('.companion-row').count(),5);assert.equal(await beta.locator('.companion-row').count(),5);
 assert.equal(await alpha.locator('.companion-row strong').first().textContent(),'A task 00');
 assert.equal(await alpha.getByText('A task 26',{exact:true}).count(),0,'noisy agent activity cannot promote an old user send');
 await alpha.getByRole('button',{name:'Show older threads (22)',exact:true}).click();
 assert.equal(await alpha.locator('.companion-row').count(),15);assert.equal(await beta.locator('.companion-row').count(),5);
 assert.ok(await alpha.getByRole('separator').count()>0);
 await alpha.getByRole('button',{name:'Show 10 more (12)',exact:true}).click();
 assert.equal(await alpha.locator('.companion-row').count(),25);
 await alpha.getByRole('button',{name:'Show 2 more (2)',exact:true}).click();
 assert.equal(await alpha.locator('.companion-row').count(),27);
 await alpha.getByRole('button',{name:'Hide older threads',exact:true}).click();
 assert.equal(await alpha.locator('.companion-row').count(),5);
 await alpha.getByRole('button',{name:'Show older threads (22)',exact:true}).click();
 await page.getByRole('textbox',{name:'Search threads',exact:true}).fill('A task 26');
 assert.equal(await page.locator('.companion-row').count(),0,'a non-live match sits under older threads');await page.getByRole('button',{name:'Show older threads (1)',exact:true}).click();assert.equal(await page.locator('.companion-row').count(),1);
 await page.getByRole('textbox',{name:'Search threads',exact:true}).fill('');
 assert.equal(await alpha.locator('.companion-row').count(),5,'search resets history paging');
 await alpha.getByRole('button',{name:/A task 00/}).click();
 await page.evaluate(()=>window.completeSyntheticThread());
 await refreshConnection(page);
 await page.waitForFunction(()=>window.hostReadAt('a-0')!==undefined);
 await page.getByRole('button',{name:'Back to threads',exact:true}).click();
 assert.equal(await alpha.getByText('A task 00',{exact:true}).count(),0,'reading a completed conversation moves it out of active rows');
 await page.getByRole('combobox',{name:'Status filter',exact:true}).selectOption('done');
 await page.getByText('A task 00',{exact:true}).waitFor();
 assert.equal(await page.locator('.companion-row').count(),1);
 await page.getByRole('combobox',{name:'Status filter',exact:true}).selectOption('all');
 assert.deepEqual(errors,[]);
 await page.locator('.companion-body [data-slot=scroll-area-viewport]').evaluate(el=>el.scrollTop=0);
 if(process.env.FREDDAI_LAYOUT_SCREENSHOTS)await page.screenshot({path:`${process.env.FREDDAI_LAYOUT_SCREENSHOTS}/phone-project-groups.png`});
 console.log('PASS default project groups, user-send sort, status-live rows + 10-row paging, independent counts, hide/reset, day labels, search, and read/Finished behavior.');
}finally{await browser.close()}
