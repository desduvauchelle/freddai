// usage: node build-audio.cjs  (cwd anywhere). Reads spec.json + remotion-project/public/vo-v2/n-*.wav, writes timelinesV2.ts, copies VO wavs into public/vo, renders music beds.
const fs = require('fs'), path = require('path'), cp = require('child_process');
const R = path.resolve(__dirname, '../remotion-project');
const spec = JSON.parse(fs.readFileSync(path.join(__dirname, 'spec.json'), 'utf8'));
const GAP = Number(process.env.GAP || 0.5);
const dur = (f) => parseFloat(cp.execFileSync('ffprobe', ['-v', 'error', '-show_entries', 'format=duration', '-of', 'csv=p=0', f]).toString());
const r2 = (x) => Math.round(x * 100) / 100;
const out = {};
for (const s of spec) {
  let t = 0.3; const vo = [];
  s.lines.forEach((text, i) => {
    const id = `${s.n}-${String(i + 1).padStart(2, '0')}`;
    const src = path.join(R, 'public/vo-v2', `n-${id}.wav`);
    const d = r2(dur(src));
    vo.push({ id, start: r2(t), duration: d, text });
    t += d + (i === 0 ? GAP + 0.1 : GAP);
    fs.copyFileSync(src, path.join(R, 'public/vo', `n-${id}.wav`));
  });
  const last = vo[vo.length - 1];
  const endcard = r2(last.start - 0.3);
  const secs = Math.ceil(last.start + last.duration + 1.45);
  const demoStart = vo[s.demo].start;
  const turn = s.turn ? r2(demoStart - 0.2) : null;
  const cues = { hook: 0, demo: r2(demoStart), endcard }; if (turn !== null) cues.turn = turn;
  const sfx = [];
  if (turn !== null) { sfx.push({ name: 'whoosh', at: turn, gain: 0.04 }, { name: 'thump', at: turn, gain: 0.5 }); }
  sfx.push({ name: 'pop', at: r2(demoStart + 0.8), gain: 0.4 }, { name: 'hit', at: r2(endcard + 0.2), gain: 0.8 });
  const music = { turn: turn ?? r2(demoStart), lift: r2(endcard - 3), hit: endcard, end: secs - 0.5 };
  out[s.slug] = { id: s.id, fps: 30, durationInFrames: secs * 30, vo, cues, music, sfx };
  cp.execFileSync('node', [path.join(R, 'tools/music-warm.cjs'), path.join(R, 'public/music', `${s.id}.wav`), JSON.stringify(music)]);
  console.log(s.n, s.slug, secs + 's', 'cues', JSON.stringify(cues));
}
const ts = `import type { ShortTimeline } from "./types";\n// GENERATED by freddai-shorts/v2/build-audio.cjs. Seconds from the start of the short. VO files public/vo/n-<id>.wav, music public/music/<tl.id>.wav.\nexport const V2_TIMELINES: Record<string, ShortTimeline> = ${JSON.stringify(out, null, 1)};\n`;
fs.writeFileSync(path.join(R, 'src/shorts/timelinesV2.ts'), ts);
